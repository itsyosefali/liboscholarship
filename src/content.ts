export interface Enquiry {
  name: string;
  service: string;
  destination: string;
  message: string;
}

export function enquiryUrl(form: Enquiry, language: Language) {
  const t = content[language];
  const service =
    t.services.find((item) => item.id === form.service)?.title ?? "";
  const lines = [
    t.waGreeting,
    "",
    `${t.waName}: ${form.name.trim()}`,
    `${t.waService}: ${service}`,
  ];
  if (form.destination.trim())
    lines.push(`${t.waDestination}: ${form.destination.trim()}`);
  if (form.message.trim()) lines.push(`${t.waMessage}: ${form.message.trim()}`);
  return `${WHATSAPP_URL}?text=${encodeURIComponent(lines.join("\n"))}`;
}
